"""
SWARIVA AI — Voice Schemas
Request and response models for voice-to-voice interaction and standalone TTS.
"""
from typing import Optional, Dict, Any
from pydantic import BaseModel, Field


class VoiceChatResponse(BaseModel):
    """Result of end-to-end voice processing (Audio In -> Text -> AI -> Audio Out)."""
    success: bool = Field(..., description="Whether voice-to-voice processing succeeded.")
    transcript: str = Field(..., description="Recognized speech text from Gnani Prisma STT.")
    detected_language: str = Field(..., description="Language detected or used for transcription.")
    response_text: str = Field(..., description="Intelligent companion response generated by the AI agent.")
    session_id: str = Field(..., description="Active session ID tracking conversation history.")
    audio_base64: Optional[str] = Field(None, description="Base64-encoded WAV speech audio from Gnani Timbre TTS.")
    processing_time_stt: float = Field(0.0, description="Prisma STT latency in seconds.")
    processing_time_tts: float = Field(0.0, description="Timbre TTS latency in seconds.")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Metadata on models, voices, and audio size.")
    error: Optional[str] = Field(None, description="Error message if processing failed.")


class TextToSpeechRequest(BaseModel):
    """Standalone TTS request (e.g., Read Aloud feature)."""
    text: str = Field(..., min_length=1, max_length=1500, description="Text to synthesize into speech.")
    language: Optional[str] = Field("auto", description="Language ('english', 'hindi', 'telugu', or 'auto').")
    voice: Optional[str] = Field(None, description="Voice name (e.g. 'Nalini', 'Kaveri', 'Deepak').")
    speed: float = Field(1.0, ge=0.5, le=2.0, description="Speech rate multiplier.")


class TextToSpeechResponse(BaseModel):
    """Result of standalone TTS synthesis."""
    success: bool
    audio_base64: Optional[str] = None
    voice: str
    language: str
    size_bytes: int = 0
    error: Optional[str] = None
